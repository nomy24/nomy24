/* --------------------------------------------------------------------------
   5. 切り口を選ぶ
   点の高い順に取ると似た案が並ぶので、系統と手間の重なりに罰点を付けて散らす。
   -------------------------------------------------------------------------- */

const MOCK_TYPES = new Set(["list", "board", "queue", "detail", "gallery", "calendar", "checklist", "form", "dashboard", "streak"]);

function matchedThemes(archetype, ctx) {
  const wanted = Object.keys(archetype.when?.themes ?? {});
  return ctx.themes.filter((theme) => wanted.includes(theme.id));
}

function scoreArchetype(archetype, ctx) {
  const when = archetype.when ?? {};
  let score = when.base ?? 1;

  for (const [id, weight] of Object.entries(when.themes ?? {})) {
    const theme = ctx.themes.find((item) => item.id === id);
    if (theme) score += weight * (1 + Math.min(1.5, theme.hits / 3));
  }
  for (const [word, weight] of Object.entries(when.words ?? {})) {
    if (ctx.allText.includes(word)) score += weight;
  }
  if (when.audience?.includes(ctx.audience.id)) score += 2;
  if (when.voice && ctx.voiceRatio >= 0.4) score += 2;
  if (when.minCount && ctx.count < when.minCount) score -= 3.5;

  return score;
}

/** 系統と手間が重ならないように3つ取る */
function pickArchetypes(ctx, exclude = []) {
  const scored = ARCHETYPES.map((archetype) => ({ archetype, score: scoreArchetype(archetype, ctx) }));
  let pool = scored.filter((item) => !exclude.includes(item.archetype.id));
  if (pool.length < 3) pool = scored; // 出し尽くしたら最初に戻る

  const picked = [];
  while (picked.length < 3 && pool.length > 0) {
    let best = null;
    let bestScore = -Infinity;
    for (const item of pool) {
      const penalty = picked.reduce((sum, chosen) =>
        sum
        + (chosen.archetype.family === item.archetype.family ? 6 : 0)
        + (chosen.archetype.effort === item.archetype.effort ? 1.5 : 0)
        + (chosen.archetype.design.mock === item.archetype.design.mock ? 3 : 0), 0);
      const value = item.score - penalty;
      if (value > bestScore) { bestScore = value; best = item; }
    }
    best.rank = picked.length; // 選んだ順＝メモへの合い方の順
    picked.push(best);
    pool = pool.filter((item) => item !== best);
  }

  // 読む順は、手軽なものから。合い方の順は rank に持たせてある。
  return picked.sort((a, b) => a.archetype.effort - b.archetype.effort || b.score - a.score);
}

/* --------------------------------------------------------------------------
   6. 1案を組み立てる
   -------------------------------------------------------------------------- */

function buildScores(archetype, ctx, score, rank) {
  const build = { 1: 5, 2: 3, 3: 2 }[archetype.effort] ?? 3;
  let keep = 3;
  if (archetype.effort === 1) keep += 1;
  if (archetype.family === "collaborate" || archetype.family === "interact") keep -= 1;
  if (archetype.family === "automate") keep -= 1;
  if (score >= 10) keep += 1;

  // 3つ目の点は「効き目」ではなく「いまのメモとの合い方」。
  // 実際にどれだけ役に立つかは端末の中では測れないが、合い方なら測れる。
  let fit = [5, 4, 3][rank] ?? 3;
  if (score < 5.5) fit -= 2;
  if (score < 2.5) fit -= 1;
  if (archetype.when?.minCount && ctx.count < archetype.when.minCount) fit -= 1;
  const clamp = (value) => Math.max(1, Math.min(5, value));
  return { build: clamp(build), keep: clamp(keep), effect: clamp(fit) };
}

function buildVerdict(archetype, ctx, score, rank, harsh) {
  const hit = matchedThemes(archetype, ctx);
  const because = hit.length
    ? `「${hit.slice(0, 2).map((theme) => theme.label).join("」「")}」の話が${hit[0].hits}件出ている`
    : null;

  if (archetype.when?.minCount && ctx.count < archetype.when.minCount) {
    return {
      tone: "bad",
      text: `方向は悪くないが早い。この切り口は${archetype.when.minCount}件くらいから効いてくるもので、いまは${ctx.count}件。${harsh ? "いま作ると、空っぽの画面を眺めることになる。" : ""}メモがたまってから戻ってくること。`,
    };
  }
  if (score < 2.5) {
    return {
      tone: "bad",
      text: `メモの中に、この切り口を必要とする話がほとんど出ていない。${harsh ? "作る側が楽しいだけで、使う場面が来ない可能性が高い。" : ""}別の案を先に見ること。`,
    };
  }
  if (rank === 0) {
    return {
      tone: "ok",
      text: `${because ? `${because}。` : ""}いまのメモに一番よく合う切り口。迷うならここから始めるのが早い。`,
    };
  }
  return {
    tone: "ok",
    text: `${because ? `${because}ので、無理のある案ではない。` : "合わないとまでは言えない。"}ただし1案目とは目的が違う。両方は作らないこと。`,
  };
}

function buildPlan(entry, ctx, harsh) {
  const { archetype, score, rank } = entry;
  const design = archetype.design;
  const hit = matchedThemes(archetype, ctx);

  return {
    axis: archetype.id,
    axisLabel: archetype.label,
    family: archetype.family,
    name: archetype.name(ctx),
    lead: archetype.lead(ctx),
    scores: buildScores(archetype, ctx, score, rank),
    features: archetype.features(ctx),
    design: {
      mock: design.mock,
      dark: design.dark === true,
      pattern: design.pattern,
      layout: design.layout,
      wire: design.wire(ctx),
      interaction: design.interaction,
      palette: design.palette,
      typography: design.typography,
      motion: design.motion,
    },
    pros: archetype.pros(ctx),
    cons: archetype.cons(ctx, harsh),
    longTerm: archetype.longTerm(ctx),
    exit: archetype.exit(ctx),
    firstStep: archetype.firstStep(ctx),
    effort: archetype.effortText,
    verdict: buildVerdict(archetype, ctx, score, rank, harsh),
    watch: hit.slice(0, 2).map((theme) => `${theme.label}：${theme.watch}`),
  };
}

function buildAlternative(ctx, picked, harsh) {
  const families = new Set(picked.map((entry) => entry.archetype.family));
  const tool = families.has("collaborate")
    ? "共有の表計算ファイル1枚"
    : families.has("analyze")
      ? "紙のカレンダーに印を付けるだけの運用"
      : families.has("automate")
        ? "生成AIの画面に、たまったメモを毎週貼るだけの運用"
        : "標準のメモアプリ";

  if (!harsh) return `作らずに ${tool} で代用する手もあります。`;
  return `作らない案：${tool}で足ります。${ctx.topic}まわりのメモが${ctx.count}件のうちは、道具ではなく続ける習慣のほうが不足しています。それでも作りたいなら理由は「自分の手に合わせたいから」であって、「効率のため」ではありません。そこを取り違えると、完成した日から開かなくなります。`;
}

